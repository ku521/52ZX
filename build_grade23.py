# ---------- 通用：生成简洁思维导图 SVG ----------
def make_mindmap(title, branches):
    n = max(len(branches), 1)
    h = max(380, 64 * n + 40)
    w = 640
    cx, cy = 130, h / 2
    parts = [f'<svg viewBox="0 0 {w} {h}" width="100%" preserveAspectRatio="xMinYMin meet" '
             f'style="max-width:{w}px;height:auto;font-family:\'Microsoft YaHei\',\'微软雅黑\',sans-serif">']
    parts.append(f'<rect x="{cx-95}" y="{cy-19}" width="190" height="38" rx="9" fill="#1565c0"/>')
    parts.append(f'<text x="{cx}" y="{cy+6}" text-anchor="middle" fill="#fff" font-size="14.5">{title}</text>')
    for i, b in enumerate(branches):
        slot = (h - 50) / n
        by = 25 + i * slot + slot / 2
        bx = 400
        parts.append(f'<path d="M{cx+95},{cy} C{(cx+bx)/2},{cy} {(cx+bx)/2},{by} {bx-100},{by}" '
                     f'fill="none" stroke="#c0392b" stroke-width="1.5" stroke-opacity="0.5"/>')
        parts.append(f'<rect x="{bx-100}" y="{by-17}" width="210" height="34" rx="8" fill="#fff" stroke="#c0392b" stroke-width="1.2"/>')
        parts.append(f'<text x="{bx}" y="{by+6}" text-anchor="middle" font-size="12.5" fill="#1a1a1a">{b}</text>')
    parts.append('</svg>')
    return "".join(parts)


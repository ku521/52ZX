HIS_WORLD = ['德国', '法国', '英国', '美国', '日本', '俄国', '苏联', '欧洲', '意大利',
             '希腊', '罗马', '埃及', '印度', '美洲', '非洲', '全球', '国际', '荷', '西班牙', '葡萄牙']

def his_fallback(text):
    """零匹配时按年份/时代线索兜底"""
    years = [int(m) for m in re.findall(r'(?<!\d)(1[5-9]\d{2}|20[0-2]\d)(?!\d)', text)]
    # 世纪/年代表述
    for m in re.findall(r'(1[5-9]|20|21)世纪(\d{0,2})', text):
        base = int(m[0]) * 100 - 1
        if m[1]:
            base = int(m[0]) * 100 - 100 + int(m[1])
        years.append(base)
    is_world = sum(text.count(w) for w in HIS_WORLD)
    if years:
        yr = min(years) if min(years) >= 1500 else min(years)
        if is_world:
            return '世界史(现代)' if yr >= 1914 else '世界史(近代)'
        if yr < 1840:
            return '中国古代史'
        if yr < 1949:
            return '中国近代史'
        return '中国现代史'
    # 无年份：世界题归近代，中国题默认古代
    return '世界史(近代)' if is_world > 0 else '中国古代史'


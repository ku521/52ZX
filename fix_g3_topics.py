    print(f'===== {subj} =====')
    from collections import Counter
    final = Counter()
    for (old, new), n in sorted(m.items(), key=lambda x: str(x[0])):
        mark = '→' if old != new else '='
        print(f'  {old[:26]:28s} {mark} {new:12s} {n}')
        final[new] += n
    print('  -- 最终分布 --')
    for u, n in final.most_common():
        print(f'    {u}: {n}')
    print()


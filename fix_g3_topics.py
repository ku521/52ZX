def pol_classify(text):
    scores = {u: 0 for u in POL_UNITS}
    for u, kws in POL_KW.items():
        for kw in kws:
            n = text.count(kw)
            if n:
                scores[u] += n * (2 if len(kw) >= 4 else 1)
    for u, kws in POL_STRONG:
        for kw in kws:
            if kw in text:
                scores[u] += 12
    best = max(scores, key=scores.get)
    if scores[best] > 0:
        return best

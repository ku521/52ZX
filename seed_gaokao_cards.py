# ============ 思维导图 SVG 生成（左→右树，根+模块盒+要点） ============
def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")

def make_mindmap(title, modules):
    """modules: [(module_title, [point,...]), ...]"""
    boxw, boxh = 320, 0
    pad = 10
    line_h = 18
    gap_y = 14
    # 计算每个模块盒高度
    mod_boxes = []
    y = 20
    for mtitle, pts in modules:
        h = 22 + len(pts) * line_h + 8
        mod_boxes.append((mtitle, pts, y, h))
        y += h + gap_y
    total_h = y
    root_x, root_y = 16, total_h / 2 - 14
    root_w, root_h = 150, 30
    svg = ['<svg viewBox="0 0 %d %d" width="100%%" preserveAspectRatio="xMinYMin meet" style="max-width:760px;height:auto;font-family:\'Microsoft YaHei\',\'微软雅黑\',sans-serif">' % (root_x + root_w + 30 + boxw + 20, total_h)]
    # 连线（从根右侧中点 -> 模块盒左侧中点），平滑曲线
    rx2 = root_x + root_w
    for mtitle, pts, my, mh in mod_boxes:
        mx = root_x + root_w + 30
        myc = my + 14
        ryc = root_y + root_h / 2
        svg.append('<path d="M%.1f,%.1f C%.1f,%.1f %.1f,%.1f %.1f,%.1f" fill="none" stroke="#2c6fbb" stroke-width="1.6" stroke-opacity="0.55"/>' % (
            rx2, ryc, (rx2+mx)/2, ryc, (rx2+mx)/2, myc, mx, myc))
    # 根节点
    svg.append('<rect x="%.1f" y="%.1f" width="%d" height="%d" rx="8" fill="#eaf1fb" stroke="#2c6fbb" stroke-width="1.6"/>' % (root_x, root_y, root_w, root_h))
    svg.append('<text x="%.1f" y="%.1f" font-size="14" font-weight="700" fill="#1f3a5f" text-anchor="middle">%s</text>' % (root_x + root_w/2, root_y + 20, esc(title)))
    # 模块盒
    for mtitle, pts, my, mh in mod_boxes:
        mx = root_x + root_w + 30
        svg.append('<rect x="%.1f" y="%.1f" width="%d" height="%d" rx="8" fill="#fff" stroke="#9bbfe6" stroke-width="1.4"/>' % (mx, my, boxw, mh))
        svg.append('<text x="%.1f" y="%.1f" font-size="13" font-weight="700" fill="#17517f">%s</text>' % (mx + 10, my + 18, esc(mtitle)))
        ty = my + 18 + line_h
        for p in pts:
            svg.append('<text x="%.1f" y="%.1f" font-size="12" fill="#33414f">· %s</text>' % (mx + 12, ty, esc(p)))
            ty += line_h
    svg.append('</svg>')
    return "".join(svg)

